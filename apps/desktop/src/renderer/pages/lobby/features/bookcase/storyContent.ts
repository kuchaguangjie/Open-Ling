export function getStoryArticles(counselorId: StoryCounselorId, locale: SupportedLocale = "zh-CN") {
  return getLocalizedStoryArticles(locale).filter((article) => article.counselorId === counselorId);
}

export function getLocalizedStoryArticles(locale: SupportedLocale = "zh-CN") {
  if (locale === "zh-CN") return storyArticles;
  return storyArticles.map((article) => ({
    ...article,
    ...englishStoryContent[article.id]
  }));
}
