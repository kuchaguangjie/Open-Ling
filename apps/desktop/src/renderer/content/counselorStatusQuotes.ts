type CounselorStatusQuotePoolId = keyof typeof counselorStatusQuotePools;

export function pickRandomCounselorStatusQuote(counselorId: string, locale: SupportedLocale = "zh-CN") {
  const pool = getCounselorStatusQuotePool(counselorId, locale);
  return pool[Math.min(Math.floor(Math.random() * pool.length), pool.length - 1)];
}

export function pickStableCounselorStatusQuote(counselorId: string, seed: string, locale: SupportedLocale = "zh-CN") {
  const pool = getCounselorStatusQuotePool(counselorId, locale);
  const index = Math.abs(hashText(seed || counselorId)) % pool.length;
  return pool[index];
}

export function buildRotatingCounselorStatusQuote({
  counselorId,
  sessionId,
  restartSeed,
  rotationBucket,
  locale = "zh-CN"
}: {
  counselorId: string;
  sessionId: string;
  restartSeed: string;
  rotationBucket: number;
  locale?: SupportedLocale;
}) {
  return pickStableCounselorStatusQuote(counselorId, `${restartSeed}:${sessionId}:${rotationBucket}`, locale);
}

function getCounselorStatusQuotePool(counselorId: string, locale: SupportedLocale) {
  const id = isCounselorStatusQuotePoolId(counselorId) ? counselorId : "chengling";
  return locale === "en-US" ? englishCounselorStatusQuotePools[id] : counselorStatusQuotePools[id];
}

function isCounselorStatusQuotePoolId(counselorId: string): counselorId is CounselorStatusQuotePoolId {
  return counselorId in counselorStatusQuotePools;
}

function hashText(value: string) {
  let hash = 0;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) | 0;
  }
  return hash;
}
